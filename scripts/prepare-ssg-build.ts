import { existsSync, lstatSync, mkdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = realpathSync(resolve(dirname(fileURLToPath(import.meta.url)), '..'))
const outDir = resolve(root, '.ssg-build')
const distDir = resolve(root, 'dist')
const marker = resolve(outDir, '.yance-p7-ssg-output')

if (
  dirname(outDir) !== root
  || basename(outDir) !== '.ssg-build'
  || relative(root, outDir) !== '.ssg-build'
  || outDir === distDir
) {
  throw new Error(`Refusing unsafe SSG build cleanup path: ${outDir}`)
}

if (existsSync(outDir)) {
  const metadata = lstatSync(outDir)
  if (metadata.isSymbolicLink() || !metadata.isDirectory() || realpathSync(outDir) !== outDir) {
    throw new Error(`Refusing to clean a non-directory or redirected SSG path: ${outDir}`)
  }
  if (!existsSync(marker)) throw new Error(`Refusing to remove unrecognized contents from ${outDir}`)
  rmSync(outDir, { recursive: true })
}

mkdirSync(outDir)
writeFileSync(resolve(outDir, '.yance-p7-ssg-output'), 'Generated by the P7 static prerender build.\n', 'utf8')
console.log(`ssg-output: prepared ${outDir}`)
